import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import Script from "next/script";
import "./globals.css";
import { ModalProvider } from "@/components/Updates/modal-provider";
import { ThemeProvider } from "@/components/providers/theme-provider";
import { Toaster } from "sonner";
import OneTap from "@/components/auth/oneTap";
import DeviceCheck from "@/components/auth/deviceCheck";
import { CookieBanner } from "@/components/site/cookie-banner";
import PushSync from "@/components/site/push-sync";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" suppressHydrationWarning>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <ThemeProvider attribute="class" defaultTheme="system" enableSystem disableTransitionOnChange>
          <ModalProvider />
          {children}
          <Toaster richColors position="top-right" />
          <OneTap />
          <DeviceCheck />
          <CookieBanner />
          <PushSync publicKey={process.env.NEXT_PUBLIC_VAPID_PUBLIC_KEY ?? ""} />
        </ThemeProvider>
        {/* Offline mode (public/sw.js), and keeps the install prompt for InstallAppCard. Production only. */}
        {process.env.NODE_ENV === "production" ? (
          <Script id="register-sw" strategy="afterInteractive">
            {`if ("serviceWorker" in navigator) navigator.serviceWorker.register("/sw.js", { updateViaCache: "none" })
addEventListener("beforeinstallprompt", (e) => { window.__pwaInstallPrompt = e })`}
          </Script>
        ) : (
          // A worker left over from a local `bun start` keeps serving its cached
          // /_next/static chunks, but dev chunks reuse names → stale code, hydration errors.
          // Reload once after removal so the page runs on fresh chunks.
          <Script id="unregister-sw" strategy="afterInteractive">
            {`navigator.serviceWorker?.getRegistrations().then(async (regs) => {
  if (!regs.length) return
  await Promise.all(regs.map((r) => r.unregister()))
  await Promise.all((await caches.keys()).map((k) => caches.delete(k)))
  location.reload()
})`}
          </Script>
        )}
      </body>
    </html>
  );
}
